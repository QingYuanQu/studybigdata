# -*- coding: utf-8 -*-
"""为每个笔记目录生成 index.md 索引页，让 section 链接可点击。

用法：
    python scripts/gen_index_pages.py                  # 生成/更新全部
    python scripts/gen_index_pages.py --dry-run        # 只看会生成哪些，不写盘
    python scripts/gen_index_pages.py --docs-dir docs

规则：
    - 跳过纯资源目录（img / assets / images / pic / export 等）
    - 已存在且由本脚本生成的 index.md 会被覆盖更新
    - 已存在的人工手写 index.md（无标记）不会被动
"""
import argparse
import os
import re

SKIP_DIRS = {
    "img", "assets", "images", "pic", "pics", "export", "img_bak",
    ".git", "_site", "data", "数据", "node_modules",
    "__pycache__", "venv", ".venv", "PPT", "pdf",
}
MARKER = "<!-- generated by scripts/gen_index_pages.py -->"
H1_RE = re.compile(r"^#\s+(.+?)\s*$", re.M)


def read_title(md_path, fallback):
    try:
        with open(md_path, "r", encoding="utf-8", errors="ignore") as fh:
            head = fh.read(4096)
    except OSError:
        return fallback
    m = H1_RE.search(head)
    if m:
        return m.group(1).strip()
    return fallback


def has_md(directory, depth=3):
    if depth <= 0:
        return False
    for root, dirs, files in os.walk(directory):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS and not d.startswith(".")]
        if any(f.endswith(".md") and f != "index.md" for f in files):
            return True
    return False


def collect_entries(dir_path, depth_limit=1):
    """返回 [(显示名, 相对链接)]，只取当前层的文件与可用的子目录索引。"""
    files, subs = [], []
    for name in sorted(os.listdir(dir_path)):
        if name.startswith("."):
            continue
        full = os.path.join(dir_path, name)
        if os.path.isfile(full):
            if name.endswith(".md") and name != "index.md":
                files.append((name, full))
        elif os.path.isdir(full) and name not in SKIP_DIRS:
            subs.append((name, full))
    entries = []
    for name, full in files:
        title = read_title(full, os.path.splitext(name)[0])
        entries.append((title, name))
    for name, full in subs:
        idx = os.path.join(full, "index.md")
        if os.path.exists(idx):
            entries.append((read_title(idx, name) + " →", "%s/index.md" % name))
        elif has_md(full):
            inner = [
                f for f in sorted(os.listdir(full))
                if f.endswith(".md") and f != "index.md"
                and os.path.isfile(os.path.join(full, f))
            ]
            if inner:
                first = inner[0]
                t = read_title(os.path.join(full, first), first[:-3])
                entries.append((name + "：" + t + " →", "%s/%s" % (name, first)))
    return entries


def gen(dir_path, dry_run):
    entries = collect_entries(dir_path)
    if not entries:
        return False          # 空目录不生成索引页，避免产生无意义页面
    title = os.path.basename(dir_path.rstrip(os.sep)) or "首页"
    body = ["---", "title: %s" % title, "---", "", MARKER, "", "# %s" % title, ""]
    if entries:
        for name, link in entries:
            body.append("- [%s](./%s)" % (name, link.replace("\\", "/")))
    else:
        body.append("_（暂无内容）_")
    body.append("")
    content = "\n".join(body)
    target = os.path.join(dir_path, "index.md")
    action = "更新" if os.path.exists(target) else "新建"
    if dry_run:
        print("[%s] %s  (%d 条)" % (action, target, len(entries)))
        return False
    with open(target, "w", encoding="utf-8") as fh:
        fh.write(content)
    return True


def walk(docs_dir):
    for root, dirs, _files in os.walk(docs_dir):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS and not d.startswith(".")]
        yield root


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--docs-dir", default="docs")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    n = 0
    for d in walk(args.docs_dir):
        target = os.path.join(d, "index.md")
        if os.path.exists(target):
            with open(target, "r", encoding="utf-8", errors="ignore") as fh:
                if MARKER not in fh.read(2048):
                    print("[跳过] 人工文件 %s" % target)
                    continue
        if gen(d, args.dry_run):
            n += 1
    if not args.dry_run:
        print("已写入 %d 个索引页" % n)


if __name__ == "__main__":
    main()
